import { test, expect } from '@playwright/test';
test('S1-01/02/03/04/07: private workspace lifecycle and second-user boundary',async({browser,baseURL})=>{
  const alice=await browser.newContext({baseURL}),bob=await browser.newContext({baseURL});
  const a=await alice.newPage(),b=await bob.newPage();
  await a.goto('/workspace');await expect(a).toHaveURL(/\/login$/);
  await a.getByLabel('Email').fill('alice@example.test');
  await a.getByLabel('Password').fill('incorrect-password');
  await a.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(a.getByText('Unable to sign in. Check your details or try again later.',{exact:true})).toBeVisible();
  await a.getByLabel('Email').fill('alice@example.test');
  await a.getByLabel('Password').fill(process.env.FIXTURE_A_PASSWORD!);
  await a.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(a).toHaveURL(/\/workbench$/);
  await a.goto('/workspace');
  await expect(a.getByText('alice@example.test',{exact:true})).toBeVisible();
  await expect(a.getByText('Alice private workspace',{exact:true})).toBeVisible();
  await expect(a.getByText('Bob private workspace',{exact:true})).toHaveCount(0);
  await a.reload();await expect(a).toHaveURL(/\/workspace$/);
  const cookie=(await alice.cookies()).find(c=>c.name==='terminal_session')!;
  expect(cookie.httpOnly).toBe(true);expect(cookie.sameSite).toBe('Lax');
  const forbidden=await alice.request.get('/api/workspace/items/'+process.env.FIXTURE_B_ITEM);
  expect(forbidden.status()).toBe(404);
  const csrf=await alice.request.post('/api/auth/logout',{headers:{origin:'https://wrong.example.test'}});
  expect(csrf.status()).toBe(403);
  await b.goto('/login');
  await b.getByLabel('Email').fill('bob@example.test');await b.getByLabel('Password').fill(process.env.FIXTURE_B_PASSWORD!);
  await b.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(b).toHaveURL(/\/workbench$/);
  await b.goto('/workspace');
  await expect(b.getByText('Bob private workspace',{exact:true})).toBeVisible();
  await expect(b.getByText('Alice private workspace',{exact:true})).toHaveCount(0);
  await a.screenshot({path:'test-results/workspace-desktop.png',fullPage:true});
  await a.setViewportSize({width:390,height:844});
  await expect(a.locator('body')).toHaveJSProperty('scrollWidth',390);
  await a.screenshot({path:'test-results/workspace-mobile.png',fullPage:true});
  await a.getByRole('button',{name:'Sign out'}).click();await expect(a).toHaveURL(/\/login$/);
  await a.goto('/workspace');await expect(a).toHaveURL(/\/login$/);
  await alice.addCookies([{name:'terminal_session',value:cookie.value,url:baseURL!}]);
  expect((await alice.request.get('/api/auth/me')).status()).toBe(401);
  await alice.close();await bob.close();
});
